#!/usr/bin/env python3
"""Regenerate the fuzz_model_load seeds and vocabulary.h from the models upstream ships in tests/data.

Each seed is an upstream model.bin cut down to its first encoder/decoder layer (the loader probes
`layer_N` variables, so dropping the later ones is still a valid model), keeping seeds small.
Run from the repo root: python3 mayhem/fuzz_model_load/gen_seeds.py
"""
import os, re, struct, sys

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..")
MODELS = os.path.join(ROOT, "tests", "data", "models")
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "testsuite")
SEEDS = {
    "v2_f32": "v2/aren-transliteration",
    "v2_i8": "v2/aren-transliteration-i8",
    "v2_i16": "v2/aren-transliteration-i16",
    "v1_i16": "v1/aren-transliteration-i16",
}


def shrink(b):
    p = 0

    def u(fmt):
        nonlocal p
        s = struct.calcsize(fmt)
        v = struct.unpack_from("<" + fmt, b, p)[0]
        p += s
        return v

    def st():
        nonlocal p
        n = u("H")
        s = b[p:p + n - 1].decode()
        p += n
        return s

    bv = u("I")
    header_end = p
    if bv >= 2:
        st()
        u("I")
        header_end = p
    n = u("I")
    keep = []
    for _ in range(n):
        start = p
        name = st()
        r = u("B")
        for _ in range(r):
            u("I")
        if bv >= 4:
            u("B")
            nb = u("I")
        else:
            isz = u("B")
            nb = u("I") * isz
        p += nb
        m = re.search(r"/layer_(\d+)/", name)
        if not m or int(m.group(1)) == 0:
            keep.append(b[start:p])
    tail = b[p:]
    return b[:header_end] + struct.pack("<I", len(keep)) + b"".join(keep) + tail


def cstr(data):
    return '"' + "".join("\\x%02x" % c for c in data) + '"'


def main():
    os.makedirs(OUT, exist_ok=True)
    for name, d in SEEDS.items():
        raw = open(os.path.join(MODELS, d, "model.bin"), "rb").read()
        out = shrink(raw)
        open(os.path.join(OUT, name + ".bin"), "wb").write(out)
        print(name, len(raw), "->", len(out))
    base = os.path.join(MODELS, "v2", "aren-transliteration-i8")
    src = open(os.path.join(base, "source_vocabulary.txt"), "rb").read()
    tgt = open(os.path.join(base, "target_vocabulary.txt"), "rb").read()
    toks = [t for t in src.decode().split("\n") if t and not t.startswith("<")][:6]
    with open(os.path.join(os.path.dirname(OUT), "vocabulary.h"), "w") as f:
        f.write("// Generated by gen_seeds.py from tests/data/models/v2/aren-transliteration-i8.\n")
        f.write("#pragma once\n#include <string>\n#include <vector>\n")
        f.write("static const std::string kSourceVocabulary(%s, %d);\n" % (cstr(src), len(src)))
        f.write("static const std::string kTargetVocabulary(%s, %d);\n" % (cstr(tgt), len(tgt)))
        f.write("static const std::vector<std::string> kSourceTokens = {%s};\n"
                % ", ".join(cstr(t.encode()) for t in toks))


if __name__ == "__main__":
    sys.exit(main())
